CREATE DATABASE IF NOT EXISTS hospital_management;
USE hospital_management;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS referrals;
DROP TABLE IF EXISTS medications;
DROP TABLE IF EXISTS investigations;
DROP TABLE IF EXISTS lab_requests;
DROP TABLE IF EXISTS admissions;
DROP TABLE IF EXISTS patients;
DROP TABLE IF EXISTS staff;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE staff (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  full_name VARCHAR(100) NOT NULL,
  role ENUM('admin','doctor','nurse','receptionist','lab_technician') NOT NULL,
  specialty VARCHAR(100) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE patients (
  id INT AUTO_INCREMENT PRIMARY KEY,
  uhid VARCHAR(30) NOT NULL UNIQUE,
  full_name VARCHAR(100) NOT NULL,
  email VARCHAR(120) NOT NULL,
  age INT NOT NULL,
  gender VARCHAR(20) NOT NULL,
  mobile VARCHAR(20),
  address VARCHAR(255),
  treating_doctor_id INT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_patient_doctor FOREIGN KEY (treating_doctor_id) REFERENCES staff(id)
);

CREATE TABLE admissions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  patient_id INT NOT NULL,
  ipd_no VARCHAR(30) NOT NULL UNIQUE,
  room_no VARCHAR(20) NOT NULL,
  admitted_on DATE NOT NULL,
  discharged_on DATE NULL,
  status ENUM('Admitted','Discharged') DEFAULT 'Admitted',
  FOREIGN KEY (patient_id) REFERENCES patients(id)
);

CREATE TABLE lab_requests (
  id INT AUTO_INCREMENT PRIMARY KEY,
  patient_id INT NOT NULL,
  test_name VARCHAR(120) NOT NULL,
  sample_type VARCHAR(80),
  sample_status ENUM('Pending','Collected','Received') DEFAULT 'Pending',
  result_status ENUM('Pending','In Progress','Completed') DEFAULT 'Pending',
  result_summary VARCHAR(255),
  requested_on DATE NOT NULL,
  FOREIGN KEY (patient_id) REFERENCES patients(id)
);

CREATE TABLE investigations (
  id INT AUTO_INCREMENT PRIMARY KEY,
  patient_id INT NOT NULL,
  investigation_name VARCHAR(120) NOT NULL,
  notes VARCHAR(255),
  created_by INT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (patient_id) REFERENCES patients(id),
  FOREIGN KEY (created_by) REFERENCES staff(id)
);

CREATE TABLE medications (
  id INT AUTO_INCREMENT PRIMARY KEY,
  patient_id INT NOT NULL,
  medicine_name VARCHAR(120) NOT NULL,
  dosage VARCHAR(80),
  schedule VARCHAR(120),
  prescribed_by INT,
  prescribed_on DATE NOT NULL,
  FOREIGN KEY (patient_id) REFERENCES patients(id),
  FOREIGN KEY (prescribed_by) REFERENCES staff(id)
);

CREATE TABLE referrals (
  id INT AUTO_INCREMENT PRIMARY KEY,
  patient_id INT NOT NULL,
  suggested_specialty VARCHAR(100) NOT NULL,
  reason VARCHAR(255) NOT NULL,
  status ENUM('Suggested','Approved','Declined') DEFAULT 'Suggested',
  suggested_by INT NOT NULL,
  reviewed_by INT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  reviewed_at TIMESTAMP NULL,
  FOREIGN KEY (patient_id) REFERENCES patients(id),
  FOREIGN KEY (suggested_by) REFERENCES staff(id),
  FOREIGN KEY (reviewed_by) REFERENCES staff(id)
);

